import React, {useEffect, useMemo, useState} from 'react';
import Layout from '@theme/Layout';
import Head from '@docusaurus/Head';
import Link from '@docusaurus/Link';
import {ArrowLeft, Check, GitBranch, NotebookPen, Download, Upload, RotateCcw, ShieldCheck, Copy} from 'lucide-react';
import Toast from '@site/src/components/Toast';
import styles from './scarab.module.css';
import {SCARAB_PLATFORMS, SCARAB_STORAGE_KEY, type Severity} from '@site/src/data/scarab';

type Store = {
  checked: Record<string, boolean>;
  notes: Record<string, string>;
};

const EMPTY: Store = {checked: {}, notes: {}};

function loadStore(): Store {
  try {
    const raw = localStorage.getItem(SCARAB_STORAGE_KEY);
    if (!raw) return EMPTY;
    const parsed = JSON.parse(raw) as Partial<Store>;
    return {
      checked: parsed.checked ?? {},
      notes: parsed.notes ?? {},
    };
  } catch {
    return EMPTY;
  }
}

const SEVERITY_ORDER: Severity[] = ['critical', 'high', 'medium', 'low', 'info'];

export default function Scarab(): React.JSX.Element {
  const [platformId, setPlatformId] = useState(SCARAB_PLATFORMS[0].id);
  const [store, setStore] = useState<Store>(EMPTY);
  const [loaded, setLoaded] = useState(false);
  const [hideDone, setHideDone] = useState(false);
  const [openNotes, setOpenNotes] = useState<Record<string, boolean>>({});
  const [copied, setCopied] = useState(false);
  const [toast, setToast] = useState('');

  const showToast = (message: string): void => {
    setToast(message);
    window.setTimeout(() => setToast(''), 4000);
  };

  useEffect(() => {
    setStore(loadStore());
    setLoaded(true);
  }, []);

  useEffect(() => {
    if (!loaded) return;
    try {
      localStorage.setItem(SCARAB_STORAGE_KEY, JSON.stringify(store));
    } catch {
      /* quota — ignore */
    }
  }, [store, loaded]);

  const platform = useMemo(
    () => SCARAB_PLATFORMS.find((p) => p.id === platformId) ?? SCARAB_PLATFORMS[0],
    [platformId],
  );

  const allChecks = useMemo(() => platform.groups.flatMap((g) => g.checks.map((c) => ({...c, group: g.title}))), [platform]);
  const done = allChecks.filter((c) => store.checked[c.id]).length;
  const total = allChecks.length;
  const pct = total === 0 ? 0 : Math.round((done / total) * 100);
  const perSeverity = SEVERITY_ORDER.map((sev) => {
    const items = allChecks.filter((c) => c.severity === sev);
    return {sev, items: items.length, done: items.filter((c) => store.checked[c.id]).length};
  }).filter((x) => x.items > 0);

  const toggle = (id: string): void =>
    setStore((s) => ({...s, checked: {...s.checked, [id]: !s.checked[id]}}));

  const setNote = (id: string, note: string): void =>
    setStore((s) => ({...s, notes: {...s.notes, [id]: note}}));

  const resetPlatform = (): void => {
    if (!window.confirm(`Reset all progress for “${platform.title}”? Notes will be kept.`)) return;
    setStore((s) => {
      const checked = {...s.checked};
      for (const c of allChecks) delete checked[c.id];
      return {...s, checked};
    });
  };

  const exportMarkdown = (): void => {
    const lines: string[] = [
      `# SEKHEM — Scarab Assessment: ${platform.title}`,
      ``,
      `Date: ${new Date().toISOString().slice(0, 10)} · Progress: ${done}/${total} (${pct}%)`,
      ``,
    ];
    for (const group of platform.groups) {
      lines.push(`## ${group.title}`, '');
      for (const c of group.checks) {
        const box = store.checked[c.id] ? 'x' : ' ';
        const note = (store.notes[c.id] ?? '').trim();
        lines.push(`- [${box}] **[${c.severity.toUpperCase()}]** ${c.title}`);
        if (note) lines.push(`  - note: ${note}`);
      }
      lines.push('');
    }
    lines.push('_Generated by The Scarab — SEKHEM (github.com/sabriigsxr/sekhem)._');
    download(`scarab-${platform.id}-${new Date().toISOString().slice(0, 10)}.md`, lines.join('\n'), 'text/markdown');
    showToast('Assessment exported as Markdown');
  };

  const exportJson = (): void => {
    const payload = {v: 1, platform: platform.id, exportedAt: new Date().toISOString(), checked: store.checked, notes: store.notes};
    download(`scarab-${platform.id}.json`, JSON.stringify(payload, null, 2), 'application/json');
    showToast('Assessment exported as JSON');
  };

  const copyMarkdown = async (): Promise<void> => {
    const blob = document.getElementById('scarab-export-md');
    if (!blob) return;
    try {
      await navigator.clipboard.writeText(blob.textContent ?? '');
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      /* noop */
    }
  };

  const importJson = (file: File): void => {
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const parsed = JSON.parse(String(reader.result)) as Partial<Store> & {v?: number; platform?: string};
        if (!parsed || typeof parsed !== 'object') throw new Error('bad file');
        setStore({checked: parsed.checked ?? {}, notes: parsed.notes ?? {}});
        showToast('Assessment imported');
      } catch {
        window.alert('Import failed — expected a Scarab JSON export.');
      }
    };
    reader.readAsText(file);
  };

  return (
    <Layout>
      <Head>
        <title>The Scarab — SEKHEM Assessment Ledger</title>
        <meta
          name="description"
          content="The Scarab: a client-side assessment checklist — progress, notes and export across Web Application and API testing. Nothing leaves your browser."
        />
      </Head>

      <main className={styles.page}>
        <div className="container">
          <Link to="/" className={styles.back}><ArrowLeft size={16} /> The Codex</Link>

          <header className={styles.hero}>
            <div className="pe-eyebrow" style={{marginTop: '1rem'}}>The Scarab</div>
            <h1 className={styles.title}>The Assessment Ledger</h1>
            <p className={styles.sub}>
              Tick as you test. Progress and notes live in your browser only — export them,
              import them back, or walk away and return. Nothing leaves your machine.
            </p>
          </header>

          <div className={styles.platformTabs} role="tablist" aria-label="Choose platform">
            {SCARAB_PLATFORMS.map((p) => (
              <button
                key={p.id}
                role="tab"
                aria-selected={p.id === platformId}
                className={`${styles.platformTab} ${p.id === platformId ? styles.platformTabActive : ''}`}
                onClick={() => setPlatformId(p.id)}>
                {p.title}
              </button>
            ))}
          </div>
          <p className={styles.platformTag}>{platform.tagline}</p>

          <div className={styles.progressWrap} aria-label={`Progress ${done} of ${total} checks`}>
            <div className={styles.progressHeader}>
              <span className={styles.progressNum}>{done} / {total}</span>
              <span className={styles.progressPct}>{pct}%</span>
            </div>
            <div className={styles.progressTrack}>
              <div className={styles.progressFill} style={{width: `${pct}%`}} />
            </div>
            <div className={styles.sevRow}>
              {perSeverity.map(({sev, items, done: d}) => (
                <span key={sev} className={`${styles.sev} ${styles['sev-' + sev]}`}>
                  {sev.toUpperCase()} {d}/{items}
                </span>
              ))}
            </div>
          </div>

          <div className={styles.toolbar}>
            <label className={styles.hideDone}>
              <input type="checkbox" checked={hideDone} onChange={(e) => setHideDone(e.target.checked)} />
              Hide completed
            </label>
            <div className={styles.toolActions}>
              <button type="button" className="pe-btn pe-btn--ghost pe-btn--sm" onClick={exportMarkdown}>
                <Download size={15} /> MD
              </button>
              <button type="button" className="pe-btn pe-btn--ghost pe-btn--sm" onClick={exportJson}>
                <Download size={15} /> JSON
              </button>
              <button type="button" className="pe-btn pe-btn--ghost pe-btn--sm" onClick={copyMarkdown}>
                {copied ? <Check size={15} /> : <Copy size={15} />} {copied ? 'Copied' : 'Copy MD'}
              </button>
              <label className="pe-btn pe-btn--ghost pe-btn--sm" style={{cursor: 'pointer'}}>
                <Upload size={15} /> Import
                <input
                  type="file"
                  accept="application/json,.json"
                  style={{display: 'none'}}
                  onChange={(e) => {
                    const f = e.target.files?.[0];
                    if (f) importJson(f);
                    e.target.value = '';
                  }}
                />
              </label>
              <button type="button" className="pe-btn pe-btn--ghost pe-btn--sm" onClick={resetPlatform}>
                <RotateCcw size={15} /> Reset
              </button>
            </div>
          </div>

          {/* hidden markdown buffer for copy-to-clipboard */}
          <pre id="scarab-export-md" style={{display: 'none'}}>
            {(() => {
              const lines = [
                `# SEKHEM — Scarab Assessment: ${platform.title}`,
                `Progress: ${done}/${total} (${pct}%)`,
                '',
                ...platform.groups.flatMap((g) => [
                  `## ${g.title}`,
                  ...g.checks.map((c) => {
                    const box = store.checked[c.id] ? 'x' : ' ';
                    const note = (store.notes[c.id] ?? '').trim();
                    return `- [${box}] [${c.severity.toUpperCase()}] ${c.title}${note ? ` — note: ${note}` : ''}`;
                  }),
                  '',
                ]),
              ];
              return lines.join('\n');
            })()}
          </pre>

          {platform.groups.map((group) => {
            const visibleChecks = hideDone ? group.checks.filter((c) => !store.checked[c.id]) : group.checks;
            if (visibleChecks.length === 0) return null;
            const gDone = group.checks.filter((c) => store.checked[c.id]).length;
            return (
              <section key={group.id} className={styles.group}>
                <header className={styles.groupHead}>
                  <div>
                    <h2 className={styles.groupTitle}>{group.title}</h2>
                    <p className={styles.groupWhy}>{group.why}</p>
                  </div>
                  <span className={styles.groupCount}>{gDone}/{group.checks.length}</span>
                </header>
                <ul className={styles.list}>
                  {visibleChecks.map((c) => (
                    <li key={c.id} className={`${styles.item} ${store.checked[c.id] ? styles.itemDone : ''}`}>
                      <button
                        type="button"
                        className={styles.checkbox}
                        role="checkbox"
                        aria-checked={!!store.checked[c.id]}
                        aria-label={c.title}
                        onClick={() => toggle(c.id)}>
                        {store.checked[c.id] ? <Check size={16} strokeWidth={3} /> : null}
                      </button>
                      <div className={styles.itemBody}>
                        <span className={styles.itemText}>{c.title}</span>
                        <span className={`${styles.sevTag} ${styles['sev-' + c.severity]}`}>{c.severity}</span>
                        {openNotes[c.id] && (
                          <textarea
                            className={styles.note}
                            value={store.notes[c.id] ?? ''}
                            onChange={(e) => setNote(c.id, e.target.value)}
                            placeholder="Evidence, request IDs, payloads, conclusions…"
                            rows={2}
                          />
                        )}
                      </div>
                      <button
                        type="button"
                        className={styles.noteToggle}
                        aria-pressed={!!openNotes[c.id]}
                        aria-label="Toggle note"
                        onClick={() => setOpenNotes((s) => ({...s, [c.id]: !s[c.id]}))}>
                        <NotebookPen size={16} />
                      </button>
                    </li>
                  ))}
                </ul>
              </section>
            );
          })}

          <p className={styles.footNote}>
            <ShieldCheck size={14} /> Local-only persistence · Original content aligned to{' '}
            <a href="https://owasp.org/www-project-web-security-testing-guide/" target="_blank" rel="noopener noreferrer">OWASP WSTG</a> /{' '}
            <a href="https://owasp.org/API-Security/" target="_blank" rel="noopener noreferrer">OWASP API Security Top 10</a> ·
            The Scarab &amp; content by <strong>Dev Ahmed Sabry</strong> ·{' '}
            <a href="https://wa.me/201284123811">WhatsApp</a>
            {' '}· <GitBranch size={12} />{' '}
            <a href="https://github.com/sabriigsxr/sekhem">GitHub</a>
          </p>
        </div>
        <Toast message={toast} visible={!!toast} />
      </main>
    </Layout>
  );
}

function download(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], {type: `${mime};charset=utf-8`});
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
